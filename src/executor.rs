#[derive(Serialize, Debug)]
pub struct WipeCertificate {
    pub device: String,
    pub method: String,
    pub device_label: Option<String>,
    pub timestamp: String,
    pub success: bool,
    pub simulated: bool,
    pub operator: Option<String>,
    pub duration_seconds: u64,
    pub cert_id: String,
    pub payload_hash: String,
    pub signature_b64: Option<String>,
}

fn certificate_dir() -> PathBuf {
    let mut p = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    p.push("certificates");
    p
}

fn ensure_cert_subdirs() -> Result<(), Box<dyn Error>> {
    let dir = certificate_dir();
    fs::create_dir_all(dir.join("keys"))?;
    fs::create_dir_all(dir.join("payloads"))?;
    fs::create_dir_all(dir.join("signatures"))?;
    fs::create_dir_all(dir.join("archives"))?;
    Ok(())
}

fn save_certificate_json(cert: &WipeCertificate) -> Result<PathBuf, Box<dyn Error>> {
    ensure_cert_subdirs()?;
    let dir = certificate_dir();
    let filename = format!("wipe_certificate_{}_{}.json", cert.device, cert.timestamp.replace(':', "-").replace('+', "-").replace('Z', "Z"));
    let mut path = dir.join("archives");
    path.push(filename);
    let json = serde_json::to_string_pretty(cert)?;
    fs::write(&path, json)?;
    Ok(path)
}

